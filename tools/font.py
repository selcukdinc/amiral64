def glyph_bytes(ch):
    rows = G[ch].split("|")
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    # 5x7 in an 8x8 cell: one column of space on the left, one row of space at the bottom
    return [sum(1 << (6 - i) for i, c in enumerate(r) if c == "#") for r in rows] + [0]

def table():
    return [glyph_bytes(chr(c)) for c in range(32, 96)]

def main():
    kind, out = sys.argv[1], sys.argv[2]
    t = table()
    with open(out, "w") as f:
        if kind == "asm":
            f.write("; generated by tools/font.py: ASCII 32..95, 8 bytes per glyph\nfont_data:\n")
            for c, g in zip(range(32, 96), t):
                f.write("        .byte " + ",".join(f"${b:02X}" for b in g) + f"   ; {chr(c)!r}\n")
        else:
            f.write("/* generated by tools/font.py: ASCII 32..95, 8 bytes per glyph */\n")
            f.write("static const unsigned char font_data[64 * 8] = {\n")
            for c, g in zip(range(32, 96), t):
                f.write("    " + ",".join(f"0x{b:02X}" for b in g) + f",  /* {chr(c)} */\n".replace("*/ */", "* /"))
            f.write("};\n")

if __name__ == "__main__":
    main()
