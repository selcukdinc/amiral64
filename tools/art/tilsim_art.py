#!/usr/bin/env python3
"""Generates sw/games/tilsim/art.txt (Tilsim): playing cards (3x4 tiles), card back, charm icons, frame,
sprite digits for the floating numbers."""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pix import Canvas, block, bigs, pal

out = ["# Tilsim graphics (generated by tools/art/tilsim_art.py; edit the generator, not this file)\n"]
Z = ["000"] * 16
def P(name, cols):
    out.append(pal(name, (cols + Z)[:16]))
# card palettes: 1 ink (suit colour), 2 card face, 3 border, 4 shadow; for the J Q K portraits
# 5 gold, 6 skin, 7 hair, 8 dark gold, 9 second robe colour, 10 white highlight
