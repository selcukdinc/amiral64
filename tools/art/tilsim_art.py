small = {
 "h": [".#.#.", "#####", "#####", ".###.", "..#.."],
 "d": ["..#..", ".###.", "#####", ".###.", "..#.."],
 "c": ["..#..", ".###.", "#.#.#", "#####", "..#.."],
 "s": ["..#..", ".###.", "#####", "#####", "..#.."],
}
big = {
 "h": [".##.##.", "#######", "#######", "#######", ".#####.", "..###..", "...#..."],
 "d": ["...#...", "..###..", ".#####.", "#######", ".#####.", "..###..", "...#..."],
 "c": ["..###..", "..###..", "##.#.##", "#######", "##.#.##", "...#...", "..###.."],
 "s": ["...#...", "..###..", ".#####.", "#######", "#######", "...#...", "..###.."],
}
def edge(c, top=False, left=False, right=False, bottom=False):
    for i in range(8):
        if top: c.set(i, 0, 3)
        if left: c.set(0, i, 3)
        if right: c.set(7, i, 4); c.set(6, i, 3)
        if bottom: c.set(i, 7, 4); c.set(i, 6, 3)
    if top and left: c.set(0, 0, 0)
    if top and right: c.set(7, 0, 0); c.set(6, 0, 3)
    if bottom and left: c.set(0, 7, 0)
    if bottom and right: c.set(7, 7, 0); c.set(6, 6, 4)
def stamp(c, rows, x0, y0, col=1):
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == "#": c.set(x0 + x, y0 + y, col)
for r in "23456789TJQKA":       # rank 0 = 2 ... 12 = A
    c = Canvas(8, 8, 2); edge(c, top=True, left=True)
    g = glyphs[r]; stamp(c, g, 1 if len(g[0]) == 6 else 2, 2)
    out.append(block("tile", f"r{r}", c.text_rows(0, 0, 8, 8)))
for s in "hdcs":
    c = Canvas(8, 8, 2); edge(c, left=True); stamp(c, small[s], 2, 1)
    out.append(block("tile", f"ps{s}", c.text_rows(0, 0, 8, 8)))
for s in "hdcs":
    c = Canvas(8, 8, 2); stamp(c, big[s], 0, 0)
    out.append(block("tile", f"pb{s}", c.text_rows(0, 0, 8, 8)))
# J Q K portraits: 16x16 over the centre and right columns of card rows 1-2 (right border drawn in)
def portrait(kind):
    c = Canvas(16, 16, 2)
    for y in range(16): c.set(14, y, 3); c.set(15, y, 4)
    if kind == "K":
        c.poly([(2, 4), (3, 0), (5, 2.5), (7, 0), (9, 2.5), (11, 0), (12, 4)], 5)      # crown
        c.rect(2, 3, 12, 4, 5); c.set(7, 1, 3 if False else 1); c.set(5, 3, 9); c.set(9, 3, 9); c.set(7, 3, 1)
        c.rect(4, 5, 10, 9, 6)                                                       # face
        c.set(5, 6, 7); c.set(6, 6, 7); c.set(8, 6, 7); c.set(9, 6, 7)               # brows
        c.set(5, 7, 1); c.set(9, 7, 1)
        c.poly([(3, 8), (11, 8), (10, 12), (7, 13), (4, 12)], 7)                     # beard
        c.rect(6, 9, 8, 9, 6); c.rect(6, 10, 8, 10, 1)                               # mouth
        c.poly([(0, 16), (2, 11), (5, 12), (7, 14), (9, 12), (12, 11), (14, 16)], 1) # robe
        c.line(7, 14, 7, 15, 5); c.line(2, 12, 0, 15, 5); c.line(12, 12, 13, 15, 5)
        c.rect(11, 6, 12, 15, 8); c.disc(12, 5.5, 1.5, 5)                            # sceptre
    elif kind == "Q":
        c.poly([(4, 3), (5, 1), (7, 2), (9, 1), (10, 3)], 5); c.set(7, 1, 1)         # tiara
        c.poly([(2, 4), (12, 4), (13, 13), (11, 9), (3, 9), (1, 13)], 7)             # hair
        c.rect(4, 4, 10, 10, 6)
        c.set(5, 6, 1); c.set(9, 6, 1); c.rect(6, 8, 8, 8, 1)
        c.set(4, 9, 7); c.set(10, 9, 7)
        c.poly([(0, 16), (3, 11), (7, 12), (11, 11), (14, 16)], 1)                   # gown
        c.poly([(5, 12), (9, 12), (7, 15)], 2); c.set(7, 13, 5)                      # neckline, jewel
        c.disc(2.5, 13.5, 1.6, 9); c.set(2, 13, 10)                                  # flower
    else:  # J
        c.poly([(2, 5), (4, 1), (11, 1), (12, 5)], 1); c.rect(2, 4, 12, 5, 9)        # cap
        c.line(10, 1, 13, -1, 5); c.line(11, 2, 13, 0, 5)                            # feather
        c.rect(4, 6, 10, 10, 6); c.rect(3, 6, 3, 8, 7); c.rect(11, 6, 11, 8, 7)       # face, hair
        c.set(5, 7, 1); c.set(9, 7, 1); c.rect(6, 9, 8, 9, 1)
        c.poly([(0, 16), (2, 12), (5, 11), (9, 11), (12, 12), (14, 16)], 9)          # tunic
        c.rect(4, 11, 10, 12, 2); c.line(4, 12, 10, 12, 5)                           # collar
        c.rect(6, 13, 8, 16, 1)
        c.line(1, 6, 1, 15, 10); c.rect(0, 12, 2, 12, 5)                             # sword
    return c
for k in "JQK":
    c = portrait(k)
    for i, (x0, y0) in enumerate(((0, 0), (8, 0), (0, 8), (8, 8))):
        out.append(block("tile", f"f{k}{i}", c.text_rows(x0, y0, 8, 8)))

for name, kw in (("eT", dict(top=True)), ("eTR", dict(top=True, right=True)), ("eL", dict(left=True)), ("eC", {}),
                 ("eR", dict(right=True)), ("eBL", dict(bottom=True, left=True)), ("eB", dict(bottom=True)),
                 ("eBR", dict(bottom=True, right=True))):
    c = Canvas(8, 8, 2); edge(c, **kw)
    out.append(block("tile", name, c.text_rows(0, 0, 8, 8)))
c = Canvas(8, 8)
for y in range(8):
    for x in range(8):
        c.set(x, y, 5 if (x + y) % 4 == 0 or (x - y) % 4 == 0 else 1 if (x // 2 + y // 2) % 2 else 2)
out.append(block("tile", "back", c.text_rows(0, 0, 8, 8)))

# frame (palette ui: 1 light, 2 dark, 3 fill)
def frame_tile(kind):
    c = Canvas(8, 8, 3)
    top, bot, left, right = "T" in kind, "B" in kind, "L" in kind, "R" in kind
    for i in range(8):
        if top: c.set(i, 0, 2); c.set(i, 1, 1)
        if bot: c.set(i, 7, 2); c.set(i, 6, 1)
        if left: c.set(0, i, 2); c.set(1, i, 1)
        if right: c.set(7, i, 2); c.set(6, i, 1)
    for (cx, cy) in ((0, 0), (7, 0), (0, 7), (7, 7)):
        if (top if cy == 0 else bot) and (left if cx == 0 else right): c.set(cx, cy, 0)
    return c.text_rows(0, 0, 8, 8)
for name in ("TL", "T", "TR", "L", "C", "R", "BL", "B", "BR"):
    out.append(block("tile", f"fr{name}", frame_tile(name)))

# charm icons (16x16, palette icons): 1 black 2 white 3 red 4 orange 5 yellow 6 green 7 lgreen 8 blue 9 lblue
# 10 purple 11 grey 12 brown 13 cream 14 dark red 15 teal
def icon(fn):
    c = Canvas(16, 16); fn(c); c.outline(1); return c
def flame(c):
    c.poly([(8, 1), (13, 8), (12, 13), (8, 15), (4, 13), (3, 8), (6, 5)], 3)
    c.poly([(8, 5), (11, 10), (10, 13), (8, 14), (6, 13), (5, 10)], 4)
    c.poly([(8, 9), (9.5, 12), (8, 14), (6.5, 12)], 5)
def chip(c):
    c.disc(8, 8, 6.5, 8); c.disc(8, 8, 4.5, 9); c.disc(8, 8, 3, 2)
    for a in range(0, 360, 60):
        c.set(8 + 5.5 * math.cos(math.radians(a)), 8 + 5.5 * math.sin(math.radians(a)), 2)
def coin(c):
    c.disc(8, 8, 6.5, 12); c.disc(8, 8, 5.5, 5); c.disc(7, 7, 3.5, 13); c.rect(7, 4, 8, 11, 4); c.rect(6, 5, 9, 5, 4); c.rect(6, 10, 9, 10, 4)
def eye(c):
    c.poly([(1, 8), (8, 3), (15, 8), (8, 13)], 2); c.disc(8, 8, 3.5, 10); c.disc(8, 8, 1.6, 1); c.set(7, 7, 2)
def sprout(c):
    c.rect(7, 7, 8, 14, 6); c.poly([(8, 8), (2, 4), (3, 9)], 7); c.poly([(8, 6), (14, 1), (13, 7)], 6); c.rect(4, 14, 11, 15, 12)
def clock(c):
    c.disc(8, 8, 6.5, 13); c.ring(8, 8, 5.6, 6.5, 11); c.line(8, 8, 8, 4, 1); c.line(8, 8, 11, 9, 3); c.set(8, 8, 1)
def dice(c):
    c.rect(2, 2, 13, 13, 2); c.rect(2, 13, 13, 13, 11); c.rect(13, 2, 13, 13, 11)
    for (x, y) in ((5, 5), (8, 8), (11, 11), (5, 11), (11, 5)): c.disc(x, y, 1.1, 3)
def cards(c):
    c.poly([(2, 4), (8, 2), (10, 12), (4, 14)], 13); c.poly([(7, 3), (13, 3), (14, 13), (8, 13)], 2)
    c.disc(10, 7, 1.2, 3); c.disc(12, 7, 1.2, 3); c.poly([(9, 7.5), (13, 7.5), (11, 10)], 3)
def suit(rows, col):
    def f(c):
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch == "#":
                    c.rect(1 + x * 2, 1 + y * 2, 2 + x * 2, 2 + y * 2, col)
    return f
for name, fn in (("flame", flame), ("chip", chip), ("coin", coin), ("eye", eye), ("sprout", sprout), ("clock", clock),
                 ("dice", dice), ("cards", cards), ("ih", suit(big["h"], 3)), ("id", suit(big["d"], 4)),
                 ("ic", suit(big["c"], 10)), ("is", suit(big["s"], 8))):
    out.append(block("big", f"i_{name}", icon(fn).text_rows(0, 0, 16, 16)))

