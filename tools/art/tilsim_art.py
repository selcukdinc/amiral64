P("cblk_s", ["000", "112", "ff9", "fc2", "a70"] + FACE)
P("cred_g", ["000", "f24", "fff", "fff", "8ef"] + FACE)
P("cblk_g", ["000", "000", "fff", "fff", "8ef"] + FACE)
