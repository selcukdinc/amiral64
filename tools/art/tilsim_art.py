for k in "0123456789+x$":
    s = Canvas(16, 16)
    for y, r in enumerate(digits[k]):
        for x, ch in enumerate(r):
            if ch == "#":
                s.rect(3 + x * 2, 1 + y * 2, 4 + x * 2, 2 + y * 2, 2)
    s.outline(1)
    out.append(block("sprite", "d" + {"+": "plus", "x": "x", "$": "gold"}.get(k, k), s.text_rows(0, 0, 16, 16)))
s = Canvas(16, 16); s.poly([(8, 2), (14, 10), (10, 10), (10, 14), (6, 14), (6, 10), (2, 10)], 2); s.outline(1)
out.append(block("sprite", "arrow", s.text_rows(0, 0, 16, 16)))
s = Canvas(16, 16); s.line(8, 3, 8, 13, 2); s.line(3, 8, 13, 8, 2); s.disc(8, 8, 1.5, 2)
out.append(block("sprite", "spark", s.text_rows(0, 0, 16, 16)))
open(sys.argv[1], "w").write("\n".join(out))
