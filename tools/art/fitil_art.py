def seg_dist(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy or 1)))
    return math.hypot(px - (ax + t * vx), py - (ay + t * vy))

def flame(segs, radius):
    c = Canvas(16, 16)
    grass(c)
    for y in range(16):
        for x in range(16):
            px, py = x + 0.5, y + 0.5
            d = min(seg_dist(px, py, *s) for s in segs)
            wob = 0.6 * math.sin(px * 1.7 + py * 0.9) + 0.4 * math.sin(py * 2.3 - px * 0.7)
            t = 1 - d / (radius + wob)
            if t <= 0:
                continue
            c.set(x, y, 0xa if t < 0.14 else 9 if t < 0.3 else 8 if t < 0.46 else 7 if t < 0.62 else 6 if t < 0.8 else 5)
    return c
