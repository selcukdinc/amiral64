def grass(c, shadow=False):
    """16x16 grass cell: mid green, a darker line on the right and bottom edges (the arena grid) and a
    few lighter blades; shadow: the wall or crate above darkens the top rows"""
    c.rect(0, 0, 15, 15, 2)
    for i in range(16):
        c.set(15, i, 1); c.set(i, 15, 1)
    for (x, y) in ((3, 4), (4, 3), (10, 9), (11, 8), (6, 11), (12, 3), (2, 10)):
        c.set(x, y, 3)
    for (x, y) in ((4, 4), (11, 9), (7, 11), (12, 4)):
        c.set(x, y, 1)
    if shadow:
        for y in range(5):
            for x in range(15):
                if y < 4 or (x + y) % 2 == 0:
                    c.set(x, y, 4)

