def bomb(r, cy):
    c = Canvas(16, 16)
    grass(c)
    for y in range(16):                                   # shadow under it
        for x in range(16):
            if ((x + 0.5 - 8) / 6.0) ** 2 + ((y + 0.5 - 14) / 1.8) ** 2 <= 1:
                c.set(x, y, 4)
    c.disc(7.5, cy, r + 1, 5)
    c.disc(7.5, cy, r, 6)
    c.disc(7.0, cy + 0.6, r - 1.2, 5)
    c.disc(5.3, cy - 2.0, 1.6, 7)
    c.set(5, cy - 3, 8)
    c.rect(8, int(cy - r - 2), 10, int(cy - r - 1), 0xd)  # cap
    c.set(11, int(cy - r - 3), 9); c.set(12, int(cy - r - 4), 9); c.set(12, int(cy - r - 5), 9)
    sx, sy = 13, int(cy - r - 6)
    c.set(sx, sy, 0xa)
    for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1)):
        c.set(sx + dx, sy + dy, 0xb)
    for dx, dy in ((-1, -1), (1, 1), (1, -1)):
        c.set(sx + dx, sy + dy, 0xc)
    return c
