def star(on):
    c = Canvas(8, 8)
    pts = [(4 + (3.6 if i % 2 == 0 else 1.5) * math.sin(i * math.pi / 5), 4.3 - (3.6 if i % 2 == 0 else 1.5) * math.cos(i * math.pi / 5)) for i in range(10)]
