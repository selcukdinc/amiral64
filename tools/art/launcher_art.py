#!/usr/bin/env python3
"""Generates sw/games/launcher/art.txt: background, card frame, button, game icons (32x32), sprites."""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pix import Canvas, block, bigs, tiles, pal

out = ["# Launcher graphics (generated by tools/art/launcher_art.py; edit the generator, not this file)\n"]

# palettes: bg = palette 4 (animated at run time), frame 5, frame selected 6, title 7, icons 8-14, sprites 15
out.append(pal("bg", ["000", "324", "313", "213", "203", "102", "102", "101", "001", "000", "000", "000", "000", "000", "000", "000"]))
out.append(pal("frame", ["000", "679", "345", "112", "9ab", "fff", "000", "000", "000", "000", "000", "000", "000", "000", "000", "000"]))
out.append(pal("spr", ["000", "fff", "aef", "5cf", "f8f", "ff8", "333", "f0f", "0ff", "fc0", "000", "000", "000", "000", "000", "000"]))

# background: solid band colours 1..8 and dither tiles between neighbouring bands
for k in range(1, 9):
    out.append(block("tile", f"bg{k}", ["%x" % k * 8] * 8))
for k in range(1, 8):
    rows = []
    for y in range(8):
        rows.append("".join("%x" % (k + 1 if (x + y) % 2 == 0 or y >= 6 else k) if y >= 2 else
                            ("%x" % (k + 1) if (x + y) % 4 == 0 else "%x" % k) for x in range(8)))
    out.append(block("tile", f"bgd{k}", rows))

# card frame (6x6 tiles; 1 border, 2 shadow, 3 glass, 4 highlight)
def frame_tile(kind):
    c = Canvas(8, 8, 3)
    top, bot, left, right = "T" in kind, "B" in kind, "L" in kind, "R" in kind
    for i in range(8):
        if top: c.set(i, 0, 1); c.set(i, 1, 4)
        if bot: c.set(i, 7, 2); c.set(i, 6, 1)
        if left: c.set(0, i, 1); c.set(1, i, 4)
        if right: c.set(7, i, 2); c.set(6, i, 1)
    if top and left: c.set(0, 0, 0); c.set(1, 0, 0); c.set(0, 1, 0); c.set(1, 1, 1); c.set(2, 1, 4)
    if top and right: c.set(7, 0, 0); c.set(6, 0, 0); c.set(7, 1, 0); c.set(6, 1, 1)
    if bot and left: c.set(0, 7, 0); c.set(1, 7, 0); c.set(0, 6, 0); c.set(1, 6, 1)
    if bot and right: c.set(7, 7, 0); c.set(6, 7, 0); c.set(7, 6, 0); c.set(6, 6, 2)
    return c.text_rows(0, 0, 8, 8)
for name in ("TL", "T", "TR", "L", "C", "R", "BL", "B", "BR"):
    out.append(block("tile", f"fr{name}", frame_tile(name)))


# ---------------------------------------------------------------- icons (32x32, 2x2 bigs each)
def icon_generic():
    c = Canvas(32, 32)
    for y in range(32): c.rect(0, y, 31, y, 1 + y // 11)
    c.poly([(4, 13), (28, 13), (30, 24), (25, 27), (20, 22), (12, 22), (7, 27), (2, 24)], 5)
    c.rect(7, 15, 9, 21, 7); c.rect(5, 17, 11, 19, 7)
    c.disc(22, 16.5, 1.8, 8); c.disc(25.5, 19.5, 1.8, 9)
    c.rect(14, 18, 18, 18, 6)
    return ["111", "213", "324", "546", "ddd", "888", "222", "f55", "5f5", "000"], c

def icon_kristal():
    c = Canvas(32, 32)
    for y in range(32): c.rect(0, y, 31, y, 1 if y < 12 else 2)
    for x in range(0, 32, 5): c.disc(x + 2, 29, 4, 3)
    for x in range(1, 32, 7): c.disc(x, 31, 3, 4)
    # crystal
    c.poly([(16, 3), (25, 12), (16, 28), (7, 12)], 7)
    c.poly([(16, 3), (25, 12), (16, 12)], 8)
    c.poly([(7, 12), (16, 12), (16, 28)], 9)
    c.poly([(11, 8), (16, 3), (16, 12)], 10)
    c.line(7, 12, 25, 12, 10)
    c.set(12, 7, 11); c.set(13, 7, 11); c.set(12, 6, 11)
    for (x, y) in ((27, 5), (4, 6)):
        c.set(x, y, 11); c.set(x - 1, y, 10); c.set(x + 1, y, 10); c.set(x, y - 1, 10); c.set(x, y + 1, 10)
    return ["000", "102", "201", "431", "642", "000", "000", "0ce", "8ff", "08a", "dff", "fff"], c

def icon_yildiz():
    c = Canvas(32, 32)
    for y in range(32): c.rect(0, y, 31, y, 1 if y < 16 else 2)
    for (x, y) in ((3, 4), (27, 3), (20, 9), (6, 22), (29, 26), (13, 28), (24, 18)): c.set(x, y, 3)
    c.disc(26, 7, 5, 4); c.disc(24.5, 5.5, 2.5, 5)
    c.poly([(6, 14), (20, 18), (6, 22)], 6)
    c.poly([(6, 14), (20, 18), (10, 18)], 7)
    c.rect(3, 16, 6, 20, 8); c.rect(1, 17, 3, 19, 9)
    c.disc(12, 18, 1.6, 10)
    c.rect(22, 17, 30, 18, 9)
    return ["000", "014", "026", "fff", "a52", "d84", "ccd", "88a", "f80", "ff0", "4cf"], c

def icon_fitil():
    c = Canvas(32, 32)
    for y in range(32):
        for x in range(32): c.set(x, y, 1 if ((x // 8) + (y // 8)) % 2 else 2)
    c.disc(14, 19, 10, 3)
    c.disc(11, 15, 3, 4); c.disc(10, 14, 1.2, 5)
    c.rect(18, 7, 22, 10, 6)
    c.line(21, 7, 24, 3, 7); c.line(22, 7, 25, 3, 7)
    c.disc(26, 2.5, 2.5, 8); c.disc(26, 2.5, 1.2, 9)
    c.set(29, 1, 9); c.set(23, 1, 8); c.set(29, 5, 8)
    return ["000", "263", "374", "112", "445", "aac", "666", "ca8", "f80", "ff0"], c

def icon_olimpiyat():
    c = Canvas(32, 32)
    for y in range(32): c.rect(0, y, 31, y, 1 if y < 10 else 2 if y < 22 else 3)
    c.poly([(6, 0), (12, 0), (17, 14), (13, 16)], 4)
    c.poly([(26, 0), (20, 0), (15, 14), (19, 16)], 5)
    c.disc(16, 21, 9, 6); c.disc(16, 21, 7, 7)
    star = [(16 + (6 if i % 2 == 0 else 2.6) * math.sin(i * math.pi / 5), 21.5 - (6 if i % 2 == 0 else 2.6) * math.cos(i * math.pi / 5)) for i in range(10)]
    c.poly(star, 8)
    c.set(11, 17, 9); c.set(12, 16, 9)
    return ["000", "6bf", "8cf", "aef", "e22", "eee", "a60", "fc2", "ff8", "fff"], c

def icon_blok():
    c = Canvas(32, 32)
    for y in range(32):
        for x in range(32): c.set(x, y, 2 if x % 6 == 5 or y % 6 == 1 else 1)
    def cell(cx, cy, col):
        x0, y0 = 1 + cx * 6, 2 + cy * 6
        c.rect(x0, y0, x0 + 5, y0 + 5, col)
        c.line(x0, y0, x0 + 5, y0, 7); c.line(x0, y0, x0, y0 + 5, 7)
        c.line(x0 + 5, y0 + 1, x0 + 5, y0 + 5, 8); c.line(x0 + 1, y0 + 5, x0 + 5, y0 + 5, 8)
    for (x, y, col) in ((0, 4, 3), (1, 4, 3), (2, 4, 4), (3, 4, 4), (4, 4, 5), (0, 3, 3), (3, 3, 4), (4, 3, 5), (4, 2, 5),
                        (2, 0, 6), (2, 1, 6), (1, 1, 6), (3, 1, 6)):
        cell(x, y, col)
    return ["000", "113", "224", "e33", "3c4", "39f", "fb2", "fff", "445"], c

def icon_tilsim():
    c = Canvas(32, 32)
    for y in range(32):
        for x in range(32):
            d = math.hypot(x - 16, y - 14)
            c.set(x, y, 1 if d > 15 else 2 if d > 9 else 3)
    def card(pts, suit_c, sx, sy, spade=False):
        c.poly(pts, 4)
        if spade:
            c.disc(sx - 1.3, sy + 1, 1.6, suit_c); c.disc(sx + 1.3, sy + 1, 1.6, suit_c)
            c.poly([(sx - 3, sy + 0.5), (sx + 3, sy + 0.5), (sx, sy - 3)], suit_c)
            c.rect(int(sx) - 1, int(sy) + 2, int(sx), int(sy) + 3, suit_c)
        else:
            c.disc(sx - 1.3, sy - 1, 1.6, suit_c); c.disc(sx + 1.3, sy - 1, 1.6, suit_c)
            c.poly([(sx - 3, sy - 0.5), (sx + 3, sy - 0.5), (sx, sy + 3)], suit_c)
    card([(4, 9), (15, 6), (19, 25), (8, 28)], 5, 11.5, 15)
    c.outline(6)
    card([(14, 6), (25, 5), (27, 24), (16, 26)], 7, 20.5, 14, spade=True)
    c.line(14, 6, 25, 5, 6); c.line(25, 5, 27, 24, 6)
    c.disc(16, 27, 3.5, 8); c.disc(16, 27, 2, 9); c.disc(16, 27, 0.9, 10)
    c.set(16, 22, 9); c.set(16, 23, 8)
    return ["000", "102", "315", "53a", "fff", "e22", "111", "223", "fc2", "4cf", "000"], c

icons = [icon_generic, icon_kristal, icon_yildiz, icon_fitil, icon_olimpiyat, icon_blok, icon_tilsim]
for i, f in enumerate(icons):
    cols, cv = f()
    out.append(pal(f"icon{i}", (cols + ["000"] * 16)[:16]))
    out.append(bigs(cv, f"icon{i}", 2, 2))

# sprites (palette 15)
s = Canvas(16, 16)
s.disc(8, 8, 2.2, 3); s.disc(8, 8, 1.2, 1)
out.append(block("sprite", "dot", s.text_rows(0, 0, 16, 16)))
s = Canvas(16, 16)
s.line(8, 3, 8, 13, 2); s.line(3, 8, 13, 8, 2); s.line(6, 6, 10, 10, 3); s.line(10, 6, 6, 10, 3); s.disc(8, 8, 1.3, 1)
out.append(block("sprite", "spark", s.text_rows(0, 0, 16, 16)))
s = Canvas(16, 16)
s.disc(8, 8, 1, 4)
out.append(block("sprite", "mote", s.text_rows(0, 0, 16, 16)))

open(sys.argv[1], "w").write("\n".join(out))
