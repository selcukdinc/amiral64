def miner(view, step, tool=None):
    """view d / u / s (side, facing right); step 0/1; tool: None, 'up', 'down' (pickaxe swing), 'push'"""
    c = Canvas(16, 16)
    # legs and boots
    if view == "s":
        if step == 0:
            c.rect(6, 12, 9, 13, 10); c.rect(6, 14, 10, 15, 11)
        else:
            c.rect(4, 12, 6, 13, 10); c.rect(9, 12, 11, 13, 10)
            c.rect(3, 14, 6, 15, 11); c.rect(9, 14, 12, 15, 11)
    else:
        a = 0 if step == 0 else 1
        c.rect(5, 12, 6, 13 - a, 10); c.rect(9, 12, 10, 13 - (1 - a), 10)
        c.rect(4, 14 - a, 7, 15 - a, 11); c.rect(8, 14 - (1 - a), 11, 15 - (1 - a), 11)
    # body: blue overalls
    c.rect(4, 8, 11, 11, 8)
    c.rect(4, 11, 11, 11, 9)
    c.rect(6, 8, 9, 9, 9)
    if view == "u":
        c.rect(5, 8, 10, 10, 9)
