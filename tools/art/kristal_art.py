# ---------------------------------------------------------------- rock (on the back wall)
def rock(c, dx=0):
    back(c, 0)
    cx, cy = 7.5 + dx, 8.3
    for y in range(16):
        for x in range(16):
            d = ((x + 0.5 - cx) / 7.2) ** 2 + ((y + 0.5 - cy) / 6.9) ** 2
            if d <= 1:
                lx, ly = x + 0.5 - (cx - 2.5), y + 0.5 - (cy - 2.5)
                l = lx * lx + ly * ly
                col = 14 if l < 3 else 13 if l < 14 else 12 if l < 40 else 11
                c.set(x, y, col)
    for (x, y) in ((9, 10), (10, 9), (5, 11), (11, 6)):
        c.set(x + dx, y, 11)
    c.outline(11) if False else None
    # an outline on the back wall
    src = [row[:] for row in c.p]
    for y in range(16):
        for x in range(16):
            if src[y][x] < 11:
                if any(0 <= x + ax < 16 and 0 <= y + ay < 16 and src[y + ay][x + ax] >= 11
                       for ax, ay in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    c.p[y][x] = 1


c = Canvas(16, 16); rock(c); big("rock", c)
