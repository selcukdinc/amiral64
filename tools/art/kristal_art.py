def gem(c, size=1.0, gold=False):
    back(c, 1)
    s = size
    top, mid, bot = 2, 6, 15
    pts = [(8, 1 + (1 - s) * 4), (8 + 6.5 * s, 6), (8, 14.5 - (1 - s) * 3), (8 - 6.5 * s, 6)]
    c.poly(pts, 4)
    inner = [(8, 2.4 + (1 - s) * 4), (8 + 5.2 * s, 6), (8, 13 - (1 - s) * 3), (8 - 5.2 * s, 6)]
    shades = (10, 11, 12, 11) if gold else (5, 6, 7, 8)
    # four facets: left-top, right-top, left-bottom, right-bottom
    for y in range(16):
        for x in range(16):
            if c.get(x, y) == 4:
                # inside the inner shape?
                ins = False
                xs = []
                yc = y + 0.5
                for i in range(4):
                    (x0, y0), (x1, y1) = inner[i], inner[(i + 1) % 4]
                    if (y0 <= yc < y1) or (y1 <= yc < y0):
                        xs.append(x0 + (yc - y0) * (x1 - x0) / (y1 - y0))
                xs.sort()
                if len(xs) == 2 and xs[0] <= x + 0.5 <= xs[1]:
                    left = x + 0.5 < 8
                    upper = y + 0.5 < 6
                    k = (0 if upper else 2) + (0 if left else 1)
                    order = (3, 2, 1, 0) if not gold else (2, 1, 0, 1)
                    c.set(x, y, shades[order[k]])
    c.set(6, 4, 9); c.set(5, 5, 9); c.set(7, 3, 9)                     # the glint
    if gold:
        c.set(9, 9, 12); c.set(10, 8, 12)


c = Canvas(16, 16); gem(c, 0.85); big("gem", c)
c = Canvas(16, 16); gem(c, 1.0, True); big("gem2", c)


