def door(c, stage):
    back(c, 0)
    c.rect(1, 1, 14, 15, 13)                 # frame
    c.rect(1, 1, 14, 1, 14); c.rect(1, 1, 1, 15, 14)
    c.rect(3, 3, 12, 15, 4)                  # the opening (dark)
    if stage < 3:
        w = (3 - stage) * 3                  # the door halves slide apart
        for x in range(3, 3 + w):
            c.rect(x, 3, x, 15, 13 if x % 3 else 14)
        for x in range(12 - w + 1, 13):
            c.rect(x, 3, x, 15, 13 if x % 3 else 14)
        if stage == 0:
            c.rect(7, 8, 8, 9, 15)           # the lock's light
    if stage >= 1:
        lw = 2 * stage
        c.rect(8 - lw // 2, 6, 7 + lw // 2, 15, 15 if stage == 3 else 8)
        if stage == 3:
            c.rect(5, 5, 10, 15, 15)
            c.rect(6, 4, 9, 4, 15)
            c.rect(7, 7, 8, 15, 9)
    c.rect(1, 0, 14, 0, 14)


