def noise(x, y, seed):
    """a cheap fixed hash 0..255"""
    v = (x * 73 + y * 151 + seed * 199) & 0xFFFF
    v = (v ^ (v >> 5)) * 109 & 0xFFFF
    return (v ^ (v >> 7)) & 255


# ---------------------------------------------------------------- the cave's back wall (empty cells)
def back(c, seed):
    for y in range(16):
        for x in range(16):
            n = noise(x, y, seed)
            c.set(x, y, 1 if n < 170 else 2 if n < 236 else 3)
    # a few darker cracks
    for (x, y) in ((3 + seed, 5), (4 + seed, 6), (11 - seed, 11), (12 - seed, 12), (8, 2 + seed)):
        c.set(x, y, 1)


