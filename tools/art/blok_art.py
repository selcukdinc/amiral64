#!/usr/bin/env python3
"""Generates sw/games/blok/art.txt (Blok Yagmuru): blocks, ghost, flash, well border, panel frame,
background pattern, sprites."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pix import Canvas, block, pal

out = ["# Blok Yagmuru graphics (generated by tools/art/blok_art.py; edit the generator, not this file)\n"]
# piece colours (palettes 4..10): 1 light edge, 2 face, 3 dark edge, 4 shine
pieces = [("cyan", "aff", "2ce", "078", "fff"), ("yel", "ffa", "fd2", "a70", "fff"), ("pur", "e9f", "a4e", "526", "fdf"),
          ("grn", "afa", "3c4", "164", "efe"), ("red", "faa", "e33", "711", "fee"), ("blu", "9bf", "36f", "128", "eef"),
          ("org", "fca", "f82", "840", "ffe")]
for name, l, f, d, s in pieces:
    out.append(pal(name, ["000", l, f, d, s, "000", "000", "011", "000", "000", "000", "000", "000", "000", "000", "000"]))
# frame / ui palette 11: 1 border light, 2 border dark, 3 panel fill, 4 bg a, 5 bg b, 6 flash white, 7 well floor
out.append(pal("ui", ["000", "68a", "234", "112", "101", "102", "fff", "011", "000", "000", "000", "000", "000", "000", "000", "000"]))
out.append(pal("spr", ["000", "fff", "ff8", "fc4", "f84", "8ef", "000", "000", "000", "000", "000", "000", "000", "000", "000", "000"]))

c = Canvas(8, 8, 2)
c.rect(0, 0, 7, 0, 1); c.rect(0, 0, 0, 7, 1); c.rect(1, 7, 7, 7, 3); c.rect(7, 1, 7, 7, 3)
c.set(1, 1, 4); c.set(2, 1, 4); c.set(1, 2, 4)
out.append(block("tile", "block", c.text_rows(0, 0, 8, 8)))
c = Canvas(8, 8, 7)            # colour 7 of every piece palette = the well colour
for i in range(0, 8, 2):
    c.set(i, 0, 2); c.set(7 - i, 7, 2); c.set(0, 7 - i, 2); c.set(7, i, 2)
out.append(block("tile", "ghost", c.text_rows(0, 0, 8, 8)))
out.append(block("tile", "flash", ["66666666"] * 8))
# well inside: very dark with a faint grid dot
c = Canvas(8, 8, 7); c.set(0, 0, 3)
out.append(block("tile", "well", c.text_rows(0, 0, 8, 8)))
# background pattern: diagonal stripes in two dark tones
c = Canvas(8, 8)
for y in range(8):
    for x in range(8):
        c.set(x, y, 5 if (x + y) % 8 < 2 else 4)
out.append(block("tile", "bg", c.text_rows(0, 0, 8, 8)))
# frame pieces (same scheme as the launcher card: 1 light, 2 dark, 3 fill)
def frame_tile(kind):
    c = Canvas(8, 8, 3)
    top, bot, left, right = "T" in kind, "B" in kind, "L" in kind, "R" in kind
    for i in range(8):
        if top: c.set(i, 0, 2); c.set(i, 1, 1)
        if bot: c.set(i, 7, 2); c.set(i, 6, 1)
        if left: c.set(0, i, 2); c.set(1, i, 1)
        if right: c.set(7, i, 2); c.set(6, i, 1)
    for (cx, cy) in ((0, 0), (7, 0), (0, 7), (7, 7)):
        if (top if cy == 0 else bot) and (left if cx == 0 else right):
            c.set(cx, cy, 0)
    return c.text_rows(0, 0, 8, 8)
for name in ("TL", "T", "TR", "L", "C", "R", "BL", "B", "BR"):
    out.append(block("tile", f"fr{name}", frame_tile(name)))
# well rim: a 3-pixel border right against the well (no strip of panel colour between the rim and the
# blocks, which looked like one more column), the rest of the tile is the background pattern.
# The name says where the tile sits: wTL = above and left of the well (the well is down and right).
def well_tile(kind):
    c = Canvas(8, 8)
    for y in range(8):
        for x in range(8):
            c.set(x, y, 5 if (x + y) % 8 < 2 else 4)
            ds = []
            if "L" in kind: ds.append(7 - x)       # well to the right
            if "R" in kind: ds.append(x)
            if "T" in kind: ds.append(7 - y)       # well below
            if "B" in kind: ds.append(y)
            d = max(ds)
            if d <= 2:
                c.set(x, y, 1 if d < 2 else 2)
    return c.text_rows(0, 0, 8, 8)
for name in ("TL", "T", "TR", "L", "R", "BL", "B", "BR"):
    out.append(block("tile", f"w{name}", well_tile(name)))

s = Canvas(16, 16); s.disc(8, 8, 2.5, 3); s.disc(8, 8, 1.4, 2); s.set(8, 8, 1)
out.append(block("sprite", "spark", s.text_rows(0, 0, 16, 16)))
s = Canvas(16, 16); s.rect(6, 6, 9, 9, 5); s.rect(7, 7, 8, 8, 1)
out.append(block("sprite", "chip", s.text_rows(0, 0, 16, 16)))
open(sys.argv[1], "w").write("\n".join(out))
