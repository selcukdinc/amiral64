# ---------------------------------------------------------------- tables
# tables.s (data, for the assembly ray caster and the C code) and tables.h (the declarations)
ANG = 1024
FOV = math.radians(66)
COLS = 40
sn = [int(round(256 * math.sin(2 * math.pi * i / ANG))) for i in range(ANG + 256)]   # cos(a) = sin(a + 256)
rc = []
for i in range(ANG):
    c = abs(math.cos(2 * math.pi * i / ANG))
    rc.append(min(0x7F00, int(round(256 / c))) if c > 1e-6 else 0x7F00)          # |1 / cos a|, 8.8
half = math.tan(FOV / 2)
ca, cc = [], []
for c in range(COLS):
    a = math.atan((c + 0.5 - COLS / 2) / (COLS / 2) * half)
    ca.append(int(round(a / (2 * math.pi) * ANG)))
    cc.append(min(255, int(round(256 * math.cos(a)))))
K = 200                                    # wall height in pixels at distance 1 cell
ht = [255] + [min(255, int(round(K * 32 / i))) for i in range(1, 1024)]   # index = distance >> 3

S = ["; generated by tools/art/koridor_art.py: angles 1024 per turn, distances 8.8 cells",
     "        .export _sin_lo, _sin_hi, _recip_lo, _recip_hi, _colang_t, _colcos_t, _height_t",
     "        .rodata"]
def dat(name, vals):
    S.append(f"{name}:")
    for i in range(0, len(vals), 16):
        S.append("        .byte " + ",".join(f"${v & 255:02X}" for v in vals[i:i + 16]))
dat("_sin_lo", sn); dat("_sin_hi", [v >> 8 for v in sn])
dat("_recip_lo", rc); dat("_recip_hi", [v >> 8 for v in rc])
dat("_colang_t", ca); dat("_colcos_t", cc); dat("_height_t", ht)
open(tab_out, "w").write("\n".join(S) + "\n")
H = ["/* generated by tools/art/koridor_art.py: tables in tables.s */",
     "extern const unsigned char sin_lo[1280], sin_hi[1280], recip_lo[1024], recip_hi[1024];",
     "extern const signed char colang_t[40];",
     "extern const unsigned char colcos_t[40], height_t[1024];",
     "#define SIN(a) ((int)(sin_lo[a] | (sin_hi[a] << 8)))",
     "#define COS(a) SIN((a) + 256)"]
open(os.path.join(os.path.dirname(tab_out), "tables.h"), "w").write("\n".join(H) + "\n")
print(f"art: {art_out}, tables: {tab_out}")
