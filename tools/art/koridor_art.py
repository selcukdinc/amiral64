#!/usr/bin/env python3
"""Generates the graphics and the math tables of Koridor 64 (a first-person shooter on the 6502):

    python3 tools/art/koridor_art.py sw/games/koridor/art.txt sw/games/koridor/tables.s

Walls are drawn with 8x8 tiles, one ray per tile column. Every wall type has 4 texture columns (u) and
8 tiles per column: k = 0 full wall, k = 1..7 the wall starting k pixels down (ceiling colour above,
a light edge on the first wall row). The lower half of the view uses the same tiles flipped vertically,
with palettes whose colour 1 is the floor instead of the ceiling. Colours of a wall palette:
1 ceiling/floor, 3..14 four wall types x (dark, mid, light), 15 edge.
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pix import Canvas, block, pal

art_out, tab_out = sys.argv[1], sys.argv[2]
out = ["# Koridor 64 graphics (generated by tools/art/koridor_art.py; edit the generator, not this file)\n"]

# ---------------------------------------------------------------- palettes
CEIL, FLOOR = (0x2, 0x2, 0x3), (0x3, 0x2, 0x2)
WALLS = [  # dark, mid, light (lit), per wall type: stone, tech, brick, door
    ((0x4, 0x4, 0x5), (0x7, 0x7, 0x8), (0xA, 0xA, 0xB)),
    ((0x1, 0x3, 0x6), (0x2, 0x6, 0xA), (0x5, 0xC, 0xF)),
    ((0x5, 0x2, 0x1), (0x9, 0x4, 0x2), (0xC, 0x7, 0x4)),
    ((0x6, 0x4, 0x0), (0xB, 0x8, 0x1), (0xF, 0xD, 0x4)),
]
EDGE = (0xD, 0xD, 0xC)
SHADE = [1.0, 0.78, 0.58, 0.40]

def hx(c):
    return "%x%x%x" % c

def dim(c, f):
    return tuple(max(0, min(15, int(round(v * f)))) for v in c)

for s, f in enumerate(SHADE):
    for region, fill in (("t", CEIL), ("b", FLOOR)):
        cols = ["000", hx(fill), hx(fill)]
        for w in WALLS:
            cols += [hx(dim(c, f)) for c in w]
        cols.append(hx(dim(EDGE, f)))
        out.append(pal(f"w{s}{region}", cols))
# 10 enemy, 11 weapon, 12 items, 13 big title letters (red gradient)
out.append(pal("enemy", ["000", "101", "313", "525", "848", "b6b", "fe4", "ff9", "e22", "fff", "622", "a33", "000", "000", "000", "000"]))
out.append(pal("weapon", ["000", "111", "334", "556", "889", "bbc", "eef", "a64", "c86", "ffa", "fd4", "f82", "e31", "fff", "000", "000"]))
out.append(pal("items", ["000", "111", "fff", "e22", "f88", "bbb", "666", "fc2", "a70", "2e4", "8f8", "1a3", "4ef", "000", "000", "000"]))
out.append(pal("big", ["000", "200", "fec", "fd9", "fb7", "f95", "e73", "d52", "b31", "912", "000", "000", "000", "000", "000", "000"]))

# ---------------------------------------------------------------- wall textures (32 px wide, 8 rows)
def tex_stone():
    t = [[1] * 32 for _ in range(8)]                     # 0 dark 1 mid 2 light
    for x in (0, 11, 22):
        for y in range(8):
            t[y][x] = 0
            t[y][(x + 1) % 32] = 2
    noise = [(4, 1), (7, 5), (15, 2), (18, 6), (26, 3), (29, 0), (8, 3), (24, 7)]
    for (x, y) in noise:
        t[y][x] = 0
        t[(y + 4) % 8][(x + 2) % 32] = 2
    return t

def tex_tech():
    t = [[0] * 32 for _ in range(8)]
    for x in list(range(2, 14)) + list(range(18, 30)):
        for y in range(8):
            t[y][x] = 1
    for x in (7, 8, 23, 24):
        for y in range(8):
            t[y][x] = 2
    for x in (2, 13, 18, 29):
        for y in range(8):
            t[y][x] = 0
    t[3][4] = 2; t[3][27] = 2
    return t

def tex_brick():
    t = [[1] * 32 for _ in range(8)]
    for x in (0, 8, 16, 24):
        for y in range(8):
            t[y][x] = 0
            t[y][x + 1] = 2
    for (x, y) in ((4, 2), (12, 5), (20, 1), (28, 6), (5, 6), (21, 4)):
        t[y][x] = 0
    return t

def tex_door():
    t = [[1] * 32 for _ in range(8)]
    for x in (0, 1, 2, 29, 30, 31):
        for y in range(8):
            t[y][x] = 0
    for y in range(8):
        t[y][3] = 2; t[y][15] = 0; t[y][16] = 2
        t[y][9] = 2 if y % 4 == 0 else 1
        t[y][22] = 2 if y % 4 == 0 else 1
    return t

texs = [tex_stone(), tex_tech(), tex_brick(), tex_door()]
# only the full-wall tile of every texture column is stored; the game makes the 7 partial tiles of each
# (rows above the wall in colour 1, the first wall row in colour 15) when it starts, at 96 + w*32 + u*8 + k
for w, tx in enumerate(texs):
    base = 3 + w * 3
    for u in range(4):
        rows = ["".join("%x" % (base + tx[y][u * 8 + x]) for x in range(8)) for y in range(8)]
        out.append(block("tile", f"w{w}u{u}", rows))
out.append(block("tile", "fill", ["11111111"] * 8))
# HUD frame and icons (palette 12 items / text palettes)
c = Canvas(8, 8); c.rect(0, 0, 7, 7, 6); c.rect(0, 0, 7, 0, 5); c.rect(0, 7, 7, 7, 1)
out.append(block("tile", "hudbar", c.text_rows(0, 0, 8, 8)))
c = Canvas(8, 8); c.rect(3, 1, 4, 6, 3); c.rect(1, 3, 6, 4, 3)
out.append(block("tile", "hudcross", c.text_rows(0, 0, 8, 8)))
c = Canvas(8, 8); c.rect(2, 2, 3, 6, 7); c.rect(5, 2, 6, 6, 7); c.rect(2, 1, 3, 1, 8); c.rect(5, 1, 6, 1, 8)
out.append(block("tile", "hudammo", c.text_rows(0, 0, 8, 8)))
c = Canvas(8, 8); c.disc(4, 4, 3.2, 9); c.disc(4, 4, 1.6, 10)
out.append(block("tile", "hudkill", c.text_rows(0, 0, 8, 8)))

# ---------------------------------------------------------------- enemy: a shadow demon ("Golge"), 64x64
def demon(attack):
    c = Canvas(64, 64)
    # legs
    c.poly([(20, 44), (28, 44), (27, 62), (18, 62)], 2)
    c.poly([(36, 44), (44, 44), (46, 62), (37, 62)], 2)
    c.rect(15, 60, 28, 63, 1); c.rect(36, 60, 49, 63, 1)
    # body
    c.disc(32, 34, 15, 3)
    c.disc(29, 31, 10, 4)
    c.disc(26, 27, 4, 5)
    # horns and head
    c.poly([(19, 10), (24, 2), (26, 13)], 10); c.poly([(45, 10), (40, 2), (38, 13)], 10)
    c.disc(32, 16, 10, 3); c.disc(30, 14, 6, 4)
    # eyes
    c.disc(27.5, 15, 2.3, 6); c.disc(36.5, 15, 2.3, 6); c.set(27, 15, 7); c.set(36, 15, 7)
    # mouth
    if attack:
        c.poly([(26, 20), (38, 20), (35, 27), (29, 27)], 1)
        c.rect(28, 20, 29, 22, 9); c.rect(34, 20, 35, 22, 9)
    else:
        c.rect(28, 21, 36, 22, 1)
    # arms and claws
    if attack:
        c.poly([(17, 30), (10, 8), (14, 6), (22, 28)], 3)
        c.poly([(47, 30), (54, 8), (50, 6), (42, 28)], 3)
        for x in (9, 12, 15):
            c.line(x, 6, x - 1, 1, 9)
        for x in (49, 52, 55):
            c.line(x, 6, x + 1, 1, 9)
    else:
        c.poly([(18, 28), (6, 44), (10, 47), (22, 33)], 3)
        c.poly([(46, 28), (58, 44), (54, 47), (42, 33)], 3)
        for (x, y) in ((5, 46), (8, 48), (11, 48)):
            c.line(x, y, x - 1, y + 4, 9)
        for (x, y) in ((59, 46), (56, 48), (53, 48)):
            c.line(x, y, x + 1, y + 4, 9)
    c.outline(1)
    return c

def shrink(c, n):
    """box-filter-free downscale: the most common non-zero colour in each block (keeps outlines)"""
    f = c.w // n
    d = Canvas(n, n)
    for y in range(n):
        for x in range(n):
            cnt = {}
            for yy in range(y * f, y * f + f):
                for xx in range(x * f, x * f + f):
                    v = c.p[yy][xx]
                    cnt[v] = cnt.get(v, 0) + 1
            zero = cnt.pop(0, 0)
            if cnt and sum(cnt.values()) * 2 >= zero:
                best = max(cnt.items(), key=lambda kv: (kv[1] + (2 if kv[0] in (6, 7, 9) else 0), kv[0]))
                d.set(x, y, best[0])
    return d

def sprites(name, c):
    n = c.w // 16
    for by in range(n):
        for bx in range(n):
            out.append(block("sprite", f"{name}_{by * n + bx}", c.text_rows(bx * 16, by * 16, 16, 16)))

for fr, att in (("w", False), ("a", True)):
    big = demon(att)
    # the 64-pixel size is the 32-pixel one doubled by the game when it starts (saves 4 KB)
    sprites(f"e{fr}32", shrink(big, 32))
    sprites(f"e{fr}16", shrink(big, 16))
# dead: a smoking puddle, 32x16 (2 sprites side by side)
c = Canvas(32, 16)
for y in range(16):
    for x in range(32):
        if ((x + 0.5 - 16) / 15) ** 2 + ((y + 0.5 - 12) / 4) ** 2 <= 1:
            c.set(x, y, 3)
c.disc(10, 11, 2.5, 4); c.disc(20, 12, 3, 4); c.set(12, 12, 6); c.set(18, 11, 6)
c.poly([(6, 9), (9, 4), (10, 9)], 10); c.poly([(25, 9), (23, 5), (22, 9)], 10)
c.outline(1)
out.append(block("sprite", "dead_0", c.text_rows(0, 0, 16, 16)))
out.append(block("sprite", "dead_1", c.text_rows(16, 0, 16, 16)))

